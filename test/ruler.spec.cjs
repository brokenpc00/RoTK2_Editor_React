test('장수 번호와 다른 Rulers 번호 및 신군주를 선택해도 올바르게 저장한다', async ({ page })=>{
    await openSave(page)
    await cell(page, 41, 'rulerNum').dblclick()
    await page.getByRole('combobox').selectOption('4')
    await page.keyboard.press('Enter')
    await expect(cell(page, 41, 'rulerNum')).toHaveText('O176')
    await expect(cell(page, 41, 'family')).toHaveText('4')
    await expect(cell(page, 41, 'syn')).toHaveText('77')
    await page.keyboard.press('Enter')
    await page.getByRole('combobox').selectOption('16')
    await page.keyboard.press('Enter')
    await expect(cell(page, 41, 'rulerNum')).toHaveText('O001')
    await expect(cell(page, 41, 'family')).toHaveText('16')
    await expect(cell(page, 41, 'syn')).toHaveText('91')
    const bytes = await saveBytes(page)
    expect(bytes[32+40*36+10]).toBe(15)
    expect(bytes.readUInt16LE(32+40*36+16)).toBe(0x8000)
    const parsed = api.parseSaveFile(bytes)
    const lists = api.getOfficerLists(parsed.officers, parsed.lands)
    expect(Array.from(lists.find(l=>l.land.idx===15 && l.key==='gov').rows, o=>o.idx)).toEqual([80, 81])
    expect(Array.from(lists.find(l=>l.land.idx===20 && l.key==='gov').rows, o=>o.idx)).toEqual([255, 254, 41])
    await page.getByRole('button', { name: 'Lands', exact: true }).click()
    await expect(page.locator('tbody tr').nth(14).locator('td').nth(6)).toHaveText('O176')
})

test('맨앞 장수를 옮기면 Lands의 시작 장수 표시와 저장 주소도 바뀐다', async ({ page })=>{
    await openSave(page)
    await cell(page, 16, 'rulerNum').dblclick()
    await page.getByRole('combobox').selectOption('2')
    await page.keyboard.press('Enter')
    await page.getByRole('button', { name: 'Lands', exact: true }).click()
    await expect(page.locator('td[data-r="10"][data-f="gov"]')).toHaveText('O173')
    await expect(page.locator('td[data-r="10"][data-f="gov"]')).toHaveClass(/changed/)
    expect((await saveBytes(page)).readUInt16LE(9874+10*35+2)).toBe(88+82*36)
})

test('군주 본인은 읽기 전용이며 위치가 불명확한 군주 선택은 원본을 유지한다', async ({ page })=>{
    const bytes = makeLinkedSave()
    bytes.writeUInt16LE(0, 9874+9*35+2)
    await openSave(page, bytes)
    await cell(page, 80, 'rulerNum').click()
    await page.keyboard.press('Enter')
    await expect(page.getByRole('combobox')).toHaveCount(0)
    await expect(cell(page, 80, 'rulerNum')).toHaveAttribute('aria-readonly', 'true')
    await cell(page, 41, 'rulerNum').dblclick()
    await page.getByRole('combobox').selectOption('9')
    page.once('dialog', dialog=>dialog.accept())
    await page.keyboard.press('Enter')
    await expect(page.getByRole('combobox')).toHaveClass('invalid')
    await expect(page.getByRole('combobox')).toBeFocused()
    await page.keyboard.press('Escape')
    await expect(page.locator('td.changed')).toHaveCount(0)
    expect(await saveBytes(page)).toEqual(bytes)
})
