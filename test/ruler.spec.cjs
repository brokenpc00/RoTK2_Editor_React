const fs = require('node:fs')
const { test, expect } = require('@playwright/test')
const { makeLinkedSave, loadFileApi } = require('./fixture.cjs')
const api = loadFileApi()
const cell = (page, idx, field)=>page.locator(`#officer-${idx} td[data-f="${field}"]`)

const openSave = async (page, buffer=makeLinkedSave())=>{
    await page.goto('/')
    await page.waitForLoadState('networkidle')
    await page.locator('#saveInput').setInputFiles({ name: 'LINKS.SAV', mimeType: 'application/octet-stream', buffer })
    await expect(page.getByRole('grid', { name: 'Officers' })).toBeVisible()
}

const saveBytes = async (page)=>{
    const pending = page.waitForEvent('download')
    await page.getByRole('button', { name: '저장', exact: true }).click()
    return fs.readFileSync(await (await pending).path())
}

test('Rulers 목록으로 선택하고 자동 값·연결·포커스와 실제 저장 파일을 갱신한다', async ({ page }, testInfo)=>{
    await openSave(page)
    await page.locator('[data-sort="name"]').click()
    await cell(page, 41, 'rulerNum').click()
    await page.keyboard.press('Enter')
    const select = page.getByRole('combobox')
    await expect(select).toBeFocused()
    await expect(select.locator('option')).toHaveText(['군주 선택', '1. O255', '2. O254', '4. O176', '9. O247', '16. O001'])
    await expect(select).toHaveValue('2')
    await select.selectOption('9')
    await select.press('ArrowDown')
    await expect(select).toBeFocused()
    await expect(select).toHaveValue('16')
    await select.selectOption('9')
    await select.press('Enter')
    await expect(cell(page, 41, 'rulerNum')).toBeFocused()
    await expect(cell(page, 41, 'rulerNum')).toHaveText('O247')
    for (const [key, value] of Object.entries({ loyalty: '100', army: '10000', weapon: '10000', train: '100', syn: '60', family: '9', nextOfficer: '-' })) {
        await expect(cell(page, 41, key)).toHaveText(value)
        if (key!=='family') await expect(cell(page, 41, key)).toHaveClass(/changed/)
    }
    // 이 장수의 Family는 원래 9이므로 같은 값은 변경 표시를 하지 않는다.
    await expect(cell(page, 41, 'family')).not.toHaveClass(/changed/)
    await expect(cell(page, 2, 'nextOfficer').locator('[data-goto="officer-42"]')).toHaveCount(1)
    await expect(cell(page, 78, 'nextOfficer').locator('[data-goto="officer-41"]')).toHaveCount(1)
    await page.keyboard.press('ArrowRight')
    await expect(cell(page, 41, 'nextOfficer')).toBeFocused()
    await page.screenshot({ path: testInfo.outputPath('ruler-change.png') })
    const expected = makeLinkedSave()
    const data = api.parseSaveFile(expected)
    api.changeOfficerRuler(data.officers, data.lands, data.rulers, 41, 9)
    const bytes = await saveBytes(page)
    expect(bytes).toEqual(Buffer.from(api.buildSaveFile(new Uint8Array(expected), data.officers, data.lands)))
    const parsed = api.parseSaveFile(bytes)
    const target = api.getOfficerLists(parsed.officers, parsed.lands).find(l=>l.land.idx===10 && l.key==='gov')
    expect(Array.from(target.rows, o=>o.idx)).toEqual([9, 47, 53, 78, 41])
    await expect(cell(page, 41, 'rulerNum')).toHaveText('O247')
    await expect(cell(page, 41, 'rulerNum')).not.toHaveClass(/changed/)
})

test('선택 후 Esc 취소와 같은 군주 확정은 값·저장 바이트를 바꾸지 않는다', async ({ page })=>{
    await openSave(page)
    await cell(page, 41, 'rulerNum').dblclick()
    await page.getByRole('combobox').selectOption('9')
    await page.keyboard.press('Escape')
    await expect(cell(page, 41, 'rulerNum')).toHaveText('O254')
    await expect(page.locator('td.changed')).toHaveCount(0)
    await page.keyboard.press('Enter')
    await expect(page.getByRole('combobox')).toHaveValue('2')
    await page.keyboard.press('Enter')
    expect(await saveBytes(page)).toEqual(makeLinkedSave())
})

