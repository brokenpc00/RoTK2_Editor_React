const fs = require('node:fs')
const { test, expect } = require('@playwright/test')
const { makeNextSave, loadFileApi } = require('./fixture.cjs')
const api = loadFileApi()
const cell = (page, idx, field)=>page.locator(`#officer-${idx} td[data-f="${field}"]`)

const saveBytes = async (page)=>{
    const pending = page.waitForEvent('download')
    await page.getByRole('button', { name: '저장', exact: true }).click()
    return fs.readFileSync(await (await pending).path())
}

test.beforeEach(async ({ page })=>{
    await page.goto('/')
    await page.waitForLoadState('networkidle')
    await page.locator('#saveInput').setInputFiles({ name: 'NEXT.SAV', mimeType: 'application/octet-stream', buffer: makeNextSave() })
    await expect(page.getByRole('grid', { name: 'Officers' })).toBeVisible()
})

test('통치지역 태수 세 명을 고르고 해당 지역 장수 뒤에 넣어 저장한다', async ({ page }, testInfo)=>{
    await page.locator('[data-sort="name"]').click()
    await cell(page, 53, 'nextOfficer').dblclick()
    const landSelect = page.getByRole('combobox', { name: '통치지역 선택' })
    await expect(landSelect.locator('option')).toHaveText(['1. 통치지역(태수) 선택', '10번 땅 · O247 (9)', '11번 땅 · O240 (16)', '12번 땅 · O239 (17)'])
    await landSelect.selectOption('11')
    const afterSelect = page.getByRole('combobox', { name: '뒤에 넣을 장수 선택' })
    await expect(afterSelect).toBeFocused()
    await expect(afterSelect.locator('option')).toHaveText(['2. 뒤에 넣을 장수 선택', 'O240 (16) 뒤', 'O173 (83) 뒤', 'O146 (110) 뒤'])
    await expect(page.locator('td.changed')).toHaveCount(0)
    await afterSelect.selectOption('16')
    await afterSelect.press('Enter')
    await expect(cell(page, 53, 'nextOfficer')).toBeFocused()
    await expect(cell(page, 53, 'nextOfficer').locator('[data-goto="officer-83"]')).toHaveCount(1)
    await expect(cell(page, 47, 'nextOfficer').locator('[data-goto="officer-78"]')).toHaveCount(1)
    await expect(cell(page, 16, 'nextOfficer').locator('[data-goto="officer-53"]')).toHaveCount(1)
    await expect(page.locator('td.changed:not([data-f="nextOfficer"])')).toHaveCount(0)
    const expected = makeNextSave()
    expected.writeUInt16LE(88+77*36, 32+46*36)
    expected.writeUInt16LE(88+82*36, 32+52*36)
    expected.writeUInt16LE(88+52*36, 32+15*36)
    const bytes = await saveBytes(page)
    expect(bytes).toEqual(expected)
    const data = api.parseSaveFile(bytes)
    const lists = api.getOfficerLists(data.officers, data.lands)
    expect(Array.from(lists.find(l=>l.land.idx===11 && l.key==='gov').rows, o=>o.idx)).toEqual([16, 53, 83, 110])
    await page.screenshot({ path: testInfo.outputPath('next-link.png') })
})

test('같은 지역에서는 자신을 제외하고 군주를 포함하며 앞쪽으로도 이동한다', async ({ page })=>{
    await cell(page, 53, 'nextOfficer').dblclick()
    await page.getByRole('combobox', { name: '통치지역 선택' }).selectOption('10')
    const select = page.getByRole('combobox', { name: '뒤에 넣을 장수 선택' })
    await expect(select.locator('option')).toHaveText(['2. 뒤에 넣을 장수 선택', 'O247 (9) 뒤', 'O209 (47) 뒤', 'O178 (78) 뒤'])
    await expect(select.locator('option[value="53"]')).toHaveCount(0)
    await select.selectOption('9')
    await select.press('Enter')
    const bytes = await saveBytes(page)
    const data = api.parseSaveFile(bytes)
    expect(Array.from(api.getOfficerLists(data.officers, data.lands).find(l=>l.land.idx===10 && l.key==='gov').rows, o=>o.idx)).toEqual([9, 53, 47, 78])
})

test('방향키와 Enter만으로 두 단계를 선택하고 끝에 넣는다', async ({ page })=>{
    await cell(page, 53, 'nextOfficer').click()
    await page.keyboard.press('Enter')
    const land = page.getByRole('combobox', { name: '통치지역 선택' })
    await land.press('ArrowDown')
    await land.press('ArrowDown')
    await expect(land).toHaveValue('11')
    await land.press('Enter')
    const select = page.getByRole('combobox', { name: '뒤에 넣을 장수 선택' })
    for (let i=0; i<3; i++) await select.press('ArrowDown')
    await expect(select).toHaveValue('110')
    await select.press('Enter')
    await expect(cell(page, 53, 'nextOfficer')).toHaveText('-')
    await expect(cell(page, 53, 'nextOfficer')).toBeFocused()
    await expect(cell(page, 110, 'nextOfficer').locator('[data-goto="officer-53"]')).toHaveCount(1)
})

test('어느 단계에서든 Esc로 취소하고 미완성 선택은 밖을 클릭하면 취소한다', async ({ page })=>{
    await cell(page, 53, 'nextOfficer').dblclick()
    await page.keyboard.press('Escape')
    await expect(page.getByRole('combobox')).toHaveCount(0)
    await page.keyboard.press('Enter')
    await page.getByRole('combobox', { name: '통치지역 선택' }).selectOption('11')
    await page.getByRole('combobox', { name: '뒤에 넣을 장수 선택' }).selectOption('83')
    await page.keyboard.press('Escape')
    await expect(page.locator('td.changed')).toHaveCount(0)
    await page.keyboard.press('Enter')
    await page.getByRole('combobox', { name: '통치지역 선택' }).selectOption('12')
    await cell(page, 47, 'int').click()
    await expect(cell(page, 47, 'int')).toBeFocused()
    await expect(page.getByRole('combobox')).toHaveCount(0)
    expect(await saveBytes(page)).toEqual(makeNextSave())
})

test('두 단계를 고른 뒤 다른 셀을 클릭해도 선택한 위치에 넣는다', async ({ page })=>{
    await cell(page, 53, 'nextOfficer').dblclick()
    await page.getByRole('combobox', { name: '통치지역 선택' }).selectOption('12')
    await page.getByRole('combobox', { name: '뒤에 넣을 장수 선택' }).selectOption('68')
    await cell(page, 47, 'int').click()
    await expect(cell(page, 47, 'int')).toBeFocused()
    const data = api.parseSaveFile(await saveBytes(page))
    expect(Array.from(api.getOfficerLists(data.officers, data.lands).find(l=>l.land.idx===12 && l.key==='gov').rows, o=>o.idx)).toEqual([17, 68, 53, 94])
})

