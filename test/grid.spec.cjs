test('Lands·Taiki도 키보드 편집하며 Taiki의 화면 보정값을 정확히 저장한다', async ({ page })=>{
    await page.getByRole('button', { name: 'Lands', exact: true }).click()
    const gold = page.locator('td[data-r="20"][data-f="gold"]')
    await gold.click()
    await page.keyboard.press('Enter')
    await page.locator('td input').fill('1234')
    await page.keyboard.press('Enter')
    await expect(gold).toBeFocused()
    const save = makeSave()
    save.writeUInt16LE(1234, 9874+20*35+8)
    expect(await saveBytes(page)).toEqual(save)
    await page.locator('#resInput').setInputFiles({ name: 'TAIKI.DAT', mimeType: 'application/octet-stream', buffer: makeTaiki() })
    await page.getByRole('button', { name: 'Taiki', exact: true }).click()
    const born = page.locator('td[data-r="39"][data-f="born"]')
    await born.click()
    await page.keyboard.press('Enter')
    await expect(page.locator('td input')).toHaveValue('171')
    await page.locator('td input').fill('172')
    await page.keyboard.press('Enter')
    await expect(born).toBeFocused()
    const taiki = makeTaiki()
    taiki[6+39*39+28] = 171
    expect(await saveBytes(page, 'TAIKI 저장')).toEqual(taiki)
})
