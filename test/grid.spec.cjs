test('한글 이름을 정렬 후 편집하고 조합 중 Enter는 확정하지 않는다', async ({ page })=>{
    await page.locator('[data-sort="name"]').click()
    await cell(page, 120, 'name').click()
    await page.keyboard.press('Enter')
    const input = page.locator('td input')
    await input.fill('가나')
    await input.dispatchEvent('keydown', { key: 'Enter', isComposing: true })
    await expect(input).toBeFocused()
    await input.press('Enter')
    await expect(cell(page, 120, 'name')).toBeFocused()
    await expect(cell(page, 120, 'name')).toHaveText('가나')
    const expected = makeSave()
    const base = 32+119*36+28
    expected.set([0xb0, 0xa1, 0xb3, 0xaa, 0, 0], base)
    expect(await saveBytes(page)).toEqual(expected)
})

test('편집 중 다른 셀 클릭·정렬, 더블클릭과 잘못된 값 취소', async ({ page })=>{
    await cell(page, 80, 'int').dblclick()
    await page.locator('td input').fill('211')
    await cell(page, 81, 'war').click()
    await expect(cell(page, 80, 'int')).toHaveText('211')
    await expect(cell(page, 81, 'war')).toBeFocused()
    await page.keyboard.press('Enter')
    await page.locator('td input').fill('88')
    await page.locator('[data-sort="name"]').click()
    await expect(cell(page, 81, 'war')).toHaveText('88')
    await cell(page, 80, 'int').dblclick()
    await page.locator('td input').fill('999')
    page.once('dialog', dialog=>dialog.accept())
    await page.keyboard.press('Enter')
    await expect(page.locator('td input')).toHaveClass('invalid')
    await expect(page.locator('td input')).toBeFocused()
    await page.keyboard.press('Escape')
    await expect(cell(page, 80, 'int')).toHaveText('211')
})

for (const key of ['name', 'int', 'war', 'chm', 'loyalty', 'syn', 'family']) {
    test(`${key} 오름차순·내림차순 정렬과 번호순 복귀`, async ({ page })=>{
        const values = () => page.locator(`tbody td[data-f="${key}"] span`).allTextContents()
        const button = page.locator(`[data-sort="${key}"]`)
        for (const direction of [1, -1]) {
            await button.click()
            const shown = await values()
            const expected = [...shown].sort((a, b)=>(key==='name' ? a.localeCompare(b, 'ko') : Number(a)-Number(b))*direction)
            expect(shown).toEqual(expected)
            await expect(button.locator('..')).toHaveAttribute('aria-sort', direction===1 ? 'ascending' : 'descending')
        }
        await page.locator('[data-sort="idx"]').click()
        const ids = await page.locator('tbody tr').evaluateAll(rows=>rows.map(row=>Number(row.id.slice(8))))
        expect(ids).toEqual([...ids].sort((a, b)=>a-b))
    })
}

