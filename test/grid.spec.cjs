const fs = require('node:fs')
const { test, expect } = require('@playwright/test')
const { makeSave, makeTaiki } = require('./fixture.cjs')

const cell = (page, idx, field) => page.locator(`#officer-${idx} td[data-f="${field}"]`)
const scroll = (page) => page.locator('.table-wrap').evaluate(w=>({ top: w.scrollTop, left: w.scrollLeft }))
const saveBytes = async (page, button='저장') => {
    const pending = page.waitForEvent('download')
    await page.getByRole('button', { name: button, exact: true }).click()
    return fs.readFileSync(await (await pending).path())
}

test.beforeEach(async ({ page })=>{
    await page.goto('/')
    await page.waitForLoadState('networkidle')
    await page.locator('#saveInput').setInputFiles({ name: 'SAVEDATA.SAV', mimeType: 'application/octet-stream', buffer: makeSave() })
    await expect(page.getByRole('grid', { name: 'Officers' })).toBeVisible()
})

test('셀 포커스, 네 방향 이동, Enter 편집·확정, Esc 취소와 스크롤 유지', async ({ page }, testInfo)=>{
    await expect(cell(page, 1, 'name')).toBeFocused()
    await cell(page, 120, 'army').click()
    await expect(page.locator('td input')).toHaveCount(0)
    await page.keyboard.press('ArrowRight')
    await expect(cell(page, 120, 'weapon')).toBeFocused()
    await page.keyboard.press('ArrowUp')
    await expect(cell(page, 119, 'weapon')).toBeFocused()
    await page.keyboard.press('ArrowLeft')
    await expect(cell(page, 119, 'army')).toBeFocused()
    await page.keyboard.press('ArrowDown')
    await expect(cell(page, 120, 'army')).toBeFocused()
    await page.keyboard.press('Enter')
    const input = page.locator('td input')
    await input.fill('8500')
    for (const key of ['ArrowUp', 'ArrowDown', 'ArrowLeft', 'ArrowRight']) {
        await input.press(key)
        await expect(input).toBeFocused()
        await expect(input).toHaveValue('8500')
    }
    const before = await scroll(page)
    expect(before.top).toBeGreaterThan(0)
    expect(before.left).toBeGreaterThan(0)
    await input.press('Enter')
    expect(await scroll(page)).toEqual(before)
    await expect(cell(page, 120, 'army')).toBeFocused()
    await expect(cell(page, 120, 'army')).toHaveText('8500')
    await expect(cell(page, 120, 'army')).toHaveClass(/changed/)
    await page.keyboard.press('Enter')
    await input.fill('9000')
    await input.press('Escape')
    await expect(cell(page, 120, 'army')).toHaveText('8500')
    await expect(cell(page, 120, 'army')).toBeFocused()
    await page.keyboard.press('ArrowDown')
    await expect(cell(page, 121, 'army')).toBeFocused()
    await page.screenshot({ path: testInfo.outputPath('keyboard-focus.png') })
})

