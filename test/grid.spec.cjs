test('정렬 후 선택한 장수 수정·키보드 이동과 저장 바이트 위치', async ({ page })=>{
    await page.locator('[data-sort="name"]').click()
    const ids = await page.locator('tbody tr').evaluateAll(rows=>rows.map(row=>Number(row.id.slice(8))))
    const idx = ids[3]
    await cell(page, idx, 'int').click()
    await page.keyboard.press('ArrowDown')
    await expect(cell(page, ids[4], 'int')).toBeFocused()
    await page.keyboard.press('ArrowUp')
    await page.keyboard.press('Enter')
    await page.locator('td input').fill('211')
    await page.keyboard.press('Enter')
    await expect(cell(page, idx, 'int')).toBeFocused()
    await expect(cell(page, idx, 'int')).toHaveText('211')
    await page.locator('[data-sort="int"]').click()
    const expected = makeSave()
    expected[32+(idx-1)*36+4] = 211
    expect(await saveBytes(page)).toEqual(expected)
})

